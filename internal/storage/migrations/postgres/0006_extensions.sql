CREATE TABLE extensions (
    name TEXT PRIMARY KEY,
    version TEXT NOT NULL,
    manifest TEXT NOT NULL,
    status TEXT NOT NULL CHECK(status IN ('pending', 'active')),
    created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"'))
);

CREATE TABLE extension_tool_names (
    tool_name TEXT PRIMARY KEY,
    extension_name TEXT NOT NULL REFERENCES extensions(name) ON DELETE CASCADE
);

CREATE INDEX extension_tool_names_extension_idx ON extension_tool_names(extension_name);

CREATE TABLE extension_audit (
    sequence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id TEXT NOT NULL CHECK(length(trim(actor_id)) BETWEEN 1 AND 200),
    extension_name TEXT NOT NULL CHECK(length(trim(extension_name)) BETWEEN 1 AND 64),
    event_type TEXT NOT NULL CHECK(length(trim(event_type)) BETWEEN 1 AND 100),
    created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.US"Z"'))
);

CREATE INDEX extension_audit_name_idx ON extension_audit(extension_name, sequence DESC);

CREATE FUNCTION extension_audit_prevent_mutation_fn() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'extension audit events are immutable';
    RETURN OLD;
END;
$$;

CREATE TRIGGER extension_audit_prevent_update
BEFORE UPDATE ON extension_audit
FOR EACH ROW EXECUTE FUNCTION extension_audit_prevent_mutation_fn();

CREATE TRIGGER extension_audit_prevent_delete
BEFORE DELETE ON extension_audit
FOR EACH ROW EXECUTE FUNCTION extension_audit_prevent_mutation_fn();
